def seed_striver():
  print(f"Connecting to database: {DB_PATH}")

  with sqlite3.connect(DB_PATH) as conn:
    cur = conn.cursor()

    cur.execute("""
            CREATE TABLE IF NOT EXISTS unified_problem_catalog (
                problem_id TEXT PRIMARY KEY,
                platform TEXT,
                title TEXT,
                topic TEXT,
                difficulty TEXT,
                rating REAL,
                tags TEXT,
                url TEXT
            )
        """)

    upsert_sql = """
            INSERT INTO unified_problem_catalog (problem_id, platform, title, topic, difficulty, rating, tags, url)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(problem_id) DO UPDATE SET
                platform = excluded.platform,
                title = excluded.title,
                topic = excluded.topic,
                difficulty = excluded.difficulty,
                rating = excluded.rating,
                tags = excluded.tags,
                url = excluded.url
        """

    count = 0
    for prob in STRIVER_PROBLEMS:
      cur.execute(
          upsert_sql,
          (
              prob["id"],
              prob["platform"],
              prob["title"],
              prob["topic"],
              prob["diff"],
              prob["rating"],
              json.dumps(prob["tags"]),
              prob["url"],
          ),
      )
      count += 1

    conn.commit()
    print(
        f"\n✅ Successfully seeded {count} core Striver SDE Sheet problems!"
    )

    cur.execute(
        "SELECT platform, count(*) FROM unified_problem_catalog GROUP BY"
        " platform"
    )
    print("\nUpdated Global Problem Catalog Counts:")
    for platform, total in cur.fetchall():
      print(f"  • {platform}: {total} problems")


if __name__ == "__main__":
  seed_striver()